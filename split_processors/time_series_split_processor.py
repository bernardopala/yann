"""Schema-driven processor for chronological windowed data."""

from typing import Callable

import numpy as np

from .specs import ColumnSpec, WindowSpec
from .split_processor import PreparedSplit, SplitProcessor
from .table_transformer import TableTransformer
from .targets import TargetAdapter, TargetSpec


class TimeSeriesSplitProcessor(SplitProcessor):
    """Prepare chronological windows with rolling validation from the train tail.

    Training windows stay inside the training partition. Validation windows use
    the final ``lookback`` transformed training rows as their initial history,
    then roll through validation while keeping every validation target inside
    the validation partition.
    """

    def __init__(self, X: np.ndarray, Y: np.ndarray, train_indices: np.ndarray, validation_indices: np.ndarray, x_schema: list[ColumnSpec], target_spec: TargetSpec, window_spec: WindowSpec) -> None:
        train_indices = np.asarray(train_indices)
        validation_indices = np.asarray(validation_indices)

        if (
            train_indices.ndim == 1
            and validation_indices.ndim == 1
            and np.issubdtype(train_indices.dtype, np.integer)
            and np.issubdtype(validation_indices.dtype, np.integer)
            and len(train_indices) > 0
            and len(validation_indices) > 0
        ):
            if (
                np.any(train_indices[1:] <= train_indices[:-1])
                or np.any(validation_indices[1:] <= validation_indices[:-1])
            ):
                raise ValueError("time-series train and validation indices must be strictly increasing")
            if train_indices[-1] >= validation_indices[0]:
                raise ValueError("time-series train indices must precede validation indices")

        super().__init__(X, Y, train_indices, validation_indices)
        if not isinstance(target_spec, TargetSpec):
            raise TypeError("target_spec must be a TargetSpec")
        self.x_transformer = TableTransformer(x_schema)
        self.target_adapter: TargetAdapter = target_spec.create_adapter()
        self.window_spec = window_spec

    def prepare(self) -> PreparedSplit:
        self.x_transformer.fit(self._X_train)
        self.target_adapter.fit(self._Y_train)

        if self.window_spec.horizon > 1 and not self.target_adapter.supports_multi_step:
            raise ValueError("horizon > 1 currently supports regression targets only")

        X_train_rows = self.x_transformer.transform(self._X_train)
        X_validation_rows = self.x_transformer.transform(self._X_validation)
        Y_train_rows = self.target_adapter.targets_for_training(self._Y_train)
        Y_validation_rows = self.target_adapter.targets_for_training(self._Y_validation)
        Y_train_scoring_rows = self.target_adapter.targets_for_scoring(self._Y_train)
        Y_validation_scoring_rows = self.target_adapter.targets_for_scoring(self._Y_validation)

        X_train, Y_train = self._make_windows(X_train_rows, Y_train_rows)

        # Validation uses the end of train as historical context. The targets
        # generated by these windows still begin at the first validation row,
        # so no training target is scored as validation data.
        X_validation_context = np.concatenate(
            [X_train_rows[-self.window_spec.lookback:], X_validation_rows],
            axis=0,
        )
        Y_validation_context = np.concatenate(
            [Y_train_rows[-self.window_spec.lookback:], Y_validation_rows],
            axis=0,
        )
        Y_validation_scoring_context = np.concatenate(
            [Y_train_scoring_rows[-self.window_spec.lookback:], Y_validation_scoring_rows],
            axis=0,
        )

        X_validation, _ = self._make_windows(
            X_validation_context,
            Y_validation_context,
        )
        _, Y_train_for_scoring = self._make_windows(X_train_rows, Y_train_scoring_rows)
        _, Y_validation_for_scoring = self._make_windows(
            X_validation_context,
            Y_validation_scoring_context,
        )
        output_size = self.target_adapter.output_size * self.window_spec.horizon

        return PreparedSplit(
            X_train=X_train,
            Y_train=Y_train,
            Y_train_for_scoring=Y_train_for_scoring,
            X_validation=X_validation,
            Y_validation_for_scoring=Y_validation_for_scoring,
            input_size=X_train.shape[1],
            output_size=output_size,
        )

    def predictions_for_scoring(self, predictions: np.ndarray) -> np.ndarray:
        predictions = np.asarray(predictions)
        if self.window_spec.horizon == 1:
            return self.target_adapter.predictions_for_scoring(predictions)

        target_width = self.target_adapter.output_size
        expected_width = self.window_spec.horizon * target_width
        if predictions.ndim != 2 or predictions.shape[1] != expected_width:
            raise ValueError(f"prediction width does not match expected multi-step output width {expected_width}")

        step_predictions = predictions.reshape(len(predictions), self.window_spec.horizon, target_width)
        flat_predictions = step_predictions.reshape(-1, target_width)
        restored = self.target_adapter.predictions_for_scoring(flat_predictions)
        restored = np.asarray(restored).reshape(len(predictions), self.window_spec.horizon, target_width)
        return restored.reshape(len(predictions), -1)

    def _make_windows(self, X: np.ndarray, Y: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        X = np.asarray(X)
        Y = np.asarray(Y)
        sample_count = len(X) - self.window_spec.lookback - self.window_spec.horizon + 1

        if sample_count <= 0:
            raise ValueError("not enough samples for the requested time-series window")

        starts = range(0, sample_count, self.window_spec.stride)
        features = [X[start:start + self.window_spec.lookback] for start in starts]
        targets = [Y[start + self.window_spec.lookback:start + self.window_spec.lookback + self.window_spec.horizon] for start in starts]
        features = np.asarray(features, dtype=np.float32)
        targets = np.asarray(targets)

        if self.window_spec.horizon == 1:
            targets = targets[:, 0]
        elif targets.ndim == 3:
            targets = targets.reshape(len(targets), -1)

        # The current MLP-based training pipeline accepts only two-dimensional samples, so every time-series window is flattened.
        features = features.reshape(len(features), -1)

        return features, targets


def create_time_series_split_processor_factory(x_schema: list[ColumnSpec], target_spec: TargetSpec, window_spec: WindowSpec) -> Callable[[np.ndarray, np.ndarray, np.ndarray, np.ndarray], TimeSeriesSplitProcessor]:
    def factory(X: np.ndarray, Y: np.ndarray, train_indices: np.ndarray, validation_indices: np.ndarray) -> TimeSeriesSplitProcessor:
        return TimeSeriesSplitProcessor(X, Y, train_indices, validation_indices, x_schema, target_spec, window_spec)

    return factory
